class SceneError(ValueError):
    pass


def validate_op(op: dict[str, Any]) -> dict[str, Any]:
    if not isinstance(op, dict) or "op" not in op:
        raise SceneError(f"each op must be an object with an 'op' key, got {op!r}")
    kind = op["op"]
    if kind not in OP_SPECS:
        raise SceneError(f"unknown op {kind!r}; expected one of {sorted(OP_SPECS)}")
    required, optional = OP_SPECS[kind]
    keys = set(op) - {"op"}
    missing = required - keys
    if missing:
        raise SceneError(f"op {kind!r} is missing {sorted(missing)}")
    unknown = keys - required - optional
    if unknown:
        raise SceneError(f"op {kind!r} does not accept {sorted(unknown)}")
    if PATH <= (required | optional) and not (keys & PATH):
        raise SceneError(f"op {kind!r} needs 'points' or 'paths'")
    if kind == "polygon" and len(op["points"]) < 3:
        raise SceneError("polygon needs at least 3 points")
    if kind == "hatch" and len(op["region"]) < 3:
        raise SceneError("hatch region needs at least 3 points")
    if kind in ("painterly", "copy"):
        src = op["source"]
        if not (isinstance(src, str) or (isinstance(src, list) and src and all(isinstance(n, str) for n in src))
                or (isinstance(src, dict) and "path" in src)):
            raise SceneError(kind + ' source must be a layer name, a list of layer names, or {"path": ...}')
    if op.get("brush") is not None and op["brush"] not in PRESETS:
        raise SceneError(f"unknown brush {op['brush']!r}; presets are {sorted(PRESETS)}")
    for path in op.get("paths", [op["points"]] if "points" in op else []):
        if not path or any(not isinstance(p, (list, tuple)) or len(p) not in (2, 3) for p in path):
            raise SceneError(f"op {kind!r}: points must be non-empty lists of [x, y] or [x, y, pressure]")
    return op


@dataclass
class Layer:
    name: str
    opacity: float = 1.0
    visible: bool = True
    ops: list[dict[str, Any]] = field(default_factory=list)
    blend: str = "normal"

    def __post_init__(self) -> None:
        if self.blend not in BLEND_MODES:
            raise SceneError(f"blend must be one of {BLEND_MODES}, got {self.blend!r}")

    def add(self, op: dict[str, Any]) -> None:
        self.ops.append(validate_op(op))

    def to_dict(self) -> dict[str, Any]:
        return {"name": self.name, "opacity": self.opacity, "visible": self.visible, "blend": self.blend,
                "ops": self.ops}

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Layer:
        layer = cls(d["name"], float(d.get("opacity", 1.0)), bool(d.get("visible", True)),
                    blend=d.get("blend", "normal"))
        for op in d.get("ops", []):
            layer.add(op)
        return layer


@dataclass
class Scene:
    width: int
    height: int
    background: Any = "#ffffff"  # None for a transparent background
    layers: list[Layer] = field(default_factory=list)
    base_dir: Path | None = field(default=None, compare=False, repr=False)  # resolves relative file paths

    def __post_init__(self) -> None:
        if not (1 <= self.width <= 16384 and 1 <= self.height <= 16384):
            raise SceneError("canvas size must be between 1 and 16384 px per side")

    def layer(self, name: str) -> Layer:
        for layer in self.layers:
            if layer.name == name:
                return layer
        raise SceneError(f"no layer named {name!r}; layers are {[l.name for l in self.layers]}")

    def add_layer(self, name: str, opacity: float = 1.0, blend: str = "normal") -> Layer:
        if any(l.name == name for l in self.layers):
            raise SceneError(f"layer {name!r} already exists")
        layer = Layer(name, opacity, blend=blend)
        self.layers.append(layer)
        return layer

    def to_dict(self) -> dict[str, Any]:
        return {
            "width": self.width,
            "height": self.height,
            "background": self.background,
            "layers": [l.to_dict() for l in self.layers],
        }

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Scene:
        scene = cls(int(d["width"]), int(d["height"]), d.get("background", "#ffffff"))
        for ld in d.get("layers", []):
            scene.layers.append(Layer.from_dict(ld))
        return scene

    def save(self, path: str | Path) -> None:
        Path(path).write_text(json.dumps(self.to_dict(), indent=2))

    @classmethod
    def load(cls, path: str | Path) -> Scene:
        scene = cls.from_dict(json.loads(Path(path).read_text()))
        scene.base_dir = Path(path).resolve().parent
        return scene
