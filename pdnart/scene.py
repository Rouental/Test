"""Scene model: a canvas made of named layers, each holding a list of drawing ops.

A scene is plain data so it can be written by hand, generated by a script, or
built up tool-call by tool-call by an AI model. It round-trips through JSON:

    {
      "width": 800, "height": 600, "background": "#ffffff",
      "layers": [
        {"name": "Sky", "opacity": 1.0, "visible": true,
         "ops": [{"op": "gradient", "kind": "linear", "x0": 0, "y0": 0,
                  "x1": 0, "y1": 600, "stops": [[0, "#0b1d51"], [1, "#ff9a5a"]]}]}
      ]
    }
"""

